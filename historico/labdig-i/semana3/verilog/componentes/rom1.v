module rom1 (clock, address, data_out);
input            clock;
input      [5:0] address;
output reg [15:0] data_out;

always @ (posedge clock)
begin
    case (address)
        6'b000000: data_out = 16'b0001001010000011; // 09 - 03 = 06
        6'b000001: data_out = 16'b0001000010000111; // 08 - 07 = 01
        6'b000010: data_out = 16'b0000010000001000; // 02 + 08 = 10
        6'b000011: data_out = 16'b0000111000001000; // 07 + 08 = 15
        6'b000100: data_out = 16'b0000111010000110; // 07 - 06 = 01
        6'b000101: data_out = 16'b0000111000001000; // 07 + 08 = 15
        6'b000110: data_out = 16'b0000110010000110; // 06 - 06 = 00
        6'b000111: data_out = 16'b0000110000000100; // 06 + 04 = 10
        6'b001000: data_out = 16'b0000111010000010; // 07 - 02 = 05
        6'b001001: data_out = 16'b0000110010000101; // 06 - 05 = 01
        6'b001010: data_out = 16'b0000011000000111; // 03 + 07 = 10
        6'b001011: data_out = 16'b0000111010000100; // 07 - 04 = 03
        6'b001100: data_out = 16'b0000011000001001; // 03 + 09 = 12
        6'b001101: data_out = 16'b0001001010001001; // 09 - 09 = 00
        6'b001110: data_out = 16'b0000100000000111; // 04 + 07 = 11
        6'b001111: data_out = 16'b0001010010000010; // 10 - 02 = 08
        6'b010000: data_out = 16'b0000010000000111; // 02 + 07 = 09
        6'b010001: data_out = 16'b0001001010000001; // 09 - 01 = 08
        6'b010010: data_out = 16'b0000100000000100; // 04 + 04 = 08
        6'b010011: data_out = 16'b0000110000000011; // 06 + 03 = 09
        6'b010100: data_out = 16'b0000110010000001; // 06 - 01 = 05
        6'b010101: data_out = 16'b0001010010000001; // 10 - 01 = 09
        6'b010110: data_out = 16'b0000010000000001; // 02 + 01 = 03
        6'b010111: data_out = 16'b0001000010000111; // 08 - 07 = 01
        6'b011000: data_out = 16'b0001010010001000; // 10 - 08 = 02
        6'b011001: data_out = 16'b0001001010000011; // 09 - 03 = 06
        6'b011010: data_out = 16'b0001001010001000; // 09 - 08 = 01
        6'b011011: data_out = 16'b0001000010000111; // 08 - 07 = 01
        6'b011100: data_out = 16'b0001010000000010; // 10 + 02 = 12
        6'b011101: data_out = 16'b0000111010000001; // 07 - 01 = 06
        6'b011110: data_out = 16'b0000101010000001; // 05 - 01 = 04
        6'b011111: data_out = 16'b0000110010000010; // 06 - 02 = 04
        6'b100000: data_out = 16'b0001000000000010; // 08 + 02 = 10
        6'b100001: data_out = 16'b0001001010000111; // 09 - 07 = 02
        6'b100010: data_out = 16'b0001010000000110; // 10 + 06 = 16
        6'b100011: data_out = 16'b0001000010000100; // 08 - 04 = 04
        6'b100100: data_out = 16'b0001000000001010; // 08 + 10 = 18
        6'b100101: data_out = 16'b0001010000000001; // 10 + 01 = 11
        6'b100110: data_out = 16'b0000111000000110; // 07 + 06 = 13
        6'b100111: data_out = 16'b0001001000000001; // 09 + 01 = 10
        6'b101000: data_out = 16'b0000110010000100; // 06 - 04 = 02
        6'b101001: data_out = 16'b0000100010000100; // 04 - 04 = 00
        6'b101010: data_out = 16'b0000110000000001; // 06 + 01 = 07
        6'b101011: data_out = 16'b0000010000000011; // 02 + 03 = 05
        6'b101100: data_out = 16'b0001010000001010; // 10 + 10 = 20
        6'b101101: data_out = 16'b0000100000000011; // 04 + 03 = 07
        6'b101110: data_out = 16'b0001010010000111; // 10 - 07 = 03
        6'b101111: data_out = 16'b0001010010000011; // 10 - 03 = 07
        6'b110000: data_out = 16'b0000010010000001; // 02 - 01 = 01
        6'b110001: data_out = 16'b0000011000000100; // 03 + 04 = 07
        6'b110010: data_out = 16'b0000011000000001; // 03 + 01 = 04
        6'b110011: data_out = 16'b0001010010000110; // 10 - 06 = 04
        6'b110100: data_out = 16'b0000101000000010; // 05 + 02 = 07
        6'b110101: data_out = 16'b0000001000000001; // 01 + 01 = 02
        6'b110110: data_out = 16'b0001000010000001; // 08 - 01 = 07
        6'b110111: data_out = 16'b0000011000000100; // 03 + 04 = 07
        6'b111000: data_out = 16'b0000010010000010; // 02 - 02 = 00
