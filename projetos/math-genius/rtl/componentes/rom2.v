        6'b000100: data_out = 16'b0000010000000010; // 02 + 02 = 04
        6'b000101: data_out = 16'b0000001110000001; // 01 / 01 = 01
        6'b000110: data_out = 16'b0000011100000001; // 03 * 01 = 03
        6'b000111: data_out = 16'b0000001100000111; // 01 * 07 = 07
        6'b001000: data_out = 16'b0000100000000100; // 04 + 04 = 08
        6'b001001: data_out = 16'b0000100110000100; // 04 / 04 = 01
        6'b001010: data_out = 16'b0001000010000101; // 08 - 05 = 03
        6'b001011: data_out = 16'b0001010000000100; // 10 + 04 = 14
        6'b001100: data_out = 16'b0000011010000011; // 03 - 03 = 00
        6'b001101: data_out = 16'b0000010000000011; // 02 + 03 = 05
        6'b001110: data_out = 16'b0000100010000010; // 04 - 02 = 02
        6'b001111: data_out = 16'b0000011100000010; // 03 * 02 = 06
        6'b010000: data_out = 16'b0001010010000101; // 10 - 05 = 05
        6'b010001: data_out = 16'b0000111100000010; // 07 * 02 = 14
        6'b010010: data_out = 16'b0001000110000100; // 08 / 04 = 02
        6'b010011: data_out = 16'b0000011000000111; // 03 + 07 = 10
        6'b010100: data_out = 16'b0000011000000101; // 03 + 05 = 08
        6'b010101: data_out = 16'b0000001100001010; // 01 * 10 = 10
        6'b010110: data_out = 16'b0000001100001010; // 01 * 10 = 10
        6'b010111: data_out = 16'b0000101100000100; // 05 * 04 = 20
        6'b011000: data_out = 16'b0001001000000010; // 09 + 02 = 11
        6'b011001: data_out = 16'b0000001100000111; // 01 * 07 = 07
        6'b011010: data_out = 16'b0001010110000101; // 10 / 05 = 02
        6'b011011: data_out = 16'b0000110110000010; // 06 / 02 = 03
        6'b011100: data_out = 16'b0001000010000011; // 08 - 03 = 05
        6'b011101: data_out = 16'b0001010010000100; // 10 - 04 = 06
        6'b011110: data_out = 16'b0000101100000010; // 05 * 02 = 10
        6'b011111: data_out = 16'b0000101110000101; // 05 / 05 = 01
        6'b100000: data_out = 16'b0000111010000101; // 07 - 05 = 02
        6'b100001: data_out = 16'b0000100110000010; // 04 / 02 = 02
        6'b100010: data_out = 16'b0000110110000011; // 06 / 03 = 02
        6'b100011: data_out = 16'b0000100110000001; // 04 / 01 = 04
        6'b100100: data_out = 16'b0001010010000111; // 10 - 07 = 03
        6'b100101: data_out = 16'b0000010010000001; // 02 - 01 = 01
        6'b100110: data_out = 16'b0000100110000010; // 04 / 02 = 02
        6'b100111: data_out = 16'b0000100110000010; // 04 / 02 = 02
        6'b101000: data_out = 16'b0000100000001000; // 04 + 08 = 12
        6'b101001: data_out = 16'b0001001010000001; // 09 - 01 = 08
        6'b101010: data_out = 16'b0000001100000011; // 01 * 03 = 03
        6'b101011: data_out = 16'b0001010110000001; // 10 / 01 = 10
        6'b101100: data_out = 16'b0000111100000001; // 07 * 01 = 07
        6'b101101: data_out = 16'b0001000010000101; // 08 - 05 = 03
        6'b101110: data_out = 16'b0000010100000110; // 02 * 06 = 12
        6'b101111: data_out = 16'b0001010010000011; // 10 - 03 = 07
        6'b110000: data_out = 16'b0000001100001000; // 01 * 08 = 08
        6'b110001: data_out = 16'b0000101100000011; // 05 * 03 = 15
