        6'b111010: data_out = 16'b0000111010000010; // 07 - 02 = 05
        6'b111011: data_out = 16'b0001000010000011; // 08 - 03 = 05
        6'b111100: data_out = 16'b0000110000001001; // 06 + 09 = 15
        6'b111101: data_out = 16'b0000100000000100; // 04 + 04 = 08
        6'b111110: data_out = 16'b0000011010000001; // 03 - 01 = 02
        6'b111111: data_out = 16'b0000001000001001; // 01 + 09 = 10
    endcase
end
endmodule

