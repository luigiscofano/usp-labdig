module rom2 (clock, address, data_out);
input            clock;
input      [5:0] address;
output reg [15:0] data_out;

always @ (posedge clock)
begin
    case (address)
        6'b000000: data_out = 16'b0000010000000101; // 02 + 05 = 07
        6'b000001: data_out = 16'b0000110010000100; // 06 - 04 = 02
        6'b000001: data_out = 16'b0000110010000100; // 06 - 04 = 02
        6'b000010: data_out = 16'b0000011000001000; // 03 + 08 = 11
